# 6. 视觉记忆配置 — "记住刚才看到了什么"
# ============================================================================

@dataclass
class MemoryConfig:
    """
    短期视觉记忆（Visual Working Memory）参数（由 I4_VisualMemory 创新策略使用）。

    【核心思想】
      人类不会立刻忘记刚看过的区域。如果刚才瞥见了一个"可疑的物体"，
      即使现在在看向别处，大脑也会记住那个位置，过一会儿再回去确认。
      这就是"视觉工作记忆"——这个配置模拟的就是这种能力。

    【参数含义】
      - memory_decay（记忆衰减）= 0.85：每过一步，记忆强度 × 0.85
        10 步后：0.85^10 ≈ 0.20（只剩 20%）
        20 步后：0.85^20 ≈ 0.04（几乎遗忘）
      - memory_capacity（记忆容量）= 10：最多同时记住 10 个窗口
      - context_radius（上下文半径）= 3：影响周围 3 个窗口单位的范围
    """
    memory_decay: float = 0.85       # 每步记忆衰减因子（decay factor，0~1，越大记得越久）
    memory_capacity: int = 10        # 最多保留多少个窗口的记忆
    context_radius: int = 3          # 记忆影响的空间范围（窗口单位）


# ============================================================================
# 7. 实验配置 — "跑多少次实验、测哪些目标"
# ============================================================================

@dataclass
class ExperimentConfig:
    """
    实验运行的总配置。

    【实验流程（简化）】
      对每种策略 × 每种目标 × 每个场景 × 每次 trial（试验）：
        1. 生成一个包含目标的合成全景图
        2. 让策略去搜索
        3. 记录找到没有、用了多少步
      最后汇总所有 trial，算发现率、平均步数等指标（metrics）。
    """
    max_steps: int = 50              # 每次搜索最多观察多少步（预算 budget 用完没找到 = 失败）
    n_trials: int = 10               # 每种策略在每个目标上的重复实验次数（越大统计越稳定）
    target_categories: List[str] = field(default_factory=lambda: [
        "水杯", "汽车", "椅子", "电脑", "书本", "人"
    ])
    n_synthetic_scenes: int = 5     # 生成多少种不同的合成场景（越大泛化性 generalization 越好）
    random_seed: int = 42            # 随机种子（seed，固定后实验结果可复现 reproducible）
    enable_innovations: bool = True  # 是否启用创新策略


# ============================================================================
# 全局单例（Singleton）— 其他模块 import 这个对象就能拿到所有默认配置
# ============================================================================

config = ExperimentConfig()
