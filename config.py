# 5. 场景先验配置 — "水杯通常在桌子上"这类常识
# ============================================================================

@dataclass
class ScenePriorConfig:
    """
    目标—场景关系先验（Scene Prior）配置。

    【核心思想】
      人类找东西时不会漫无目的——你知道"水杯通常在桌子上"、"汽车通常在道路上"。
      这些常识被编码为概率表，用来引导搜索优先覆盖高概率区域。

    【数据格式说明】
      object_scene_priors[目标][场景] = 出现概率
      例如：object_scene_priors["水杯"]["桌子"] = 0.70
      意思是：在所有可能放水杯的地方中，70% 的情况水杯在桌子上。

      概率可以大于 1（它们是相对权重 weight，不是严格的概率值 probability）。

    【如何使用】
      在 I2_ScenePriorGuided 策略中，每个候选窗口计算：
        prior_score（先验分数）= Σ(窗口内某场景的面积占比 × 该场景下目标出现概率)
      然后优先观察 prior_score 最高的窗口。
    """
    object_scene_priors: Dict[str, Dict[str, float]] = field(default_factory=lambda: {
        # 目标     场景标签（label）: 概率权重
        "水杯": {"桌子": 0.70, "厨房台面": 0.20, "地板": 0.05, "墙壁": 0.00, "沙发": 0.05},
        "汽车": {"道路": 0.75, "停车场": 0.20, "建筑": 0.03, "天空": 0.00, "草地": 0.02},
        "椅子": {"桌子": 0.50, "地板": 0.30, "墙壁": 0.10, "沙发": 0.10, "床": 0.00},
        "电脑": {"桌子": 0.80, "床": 0.10, "地板": 0.05, "沙发": 0.05, "厨房台面": 0.00},
        "书本": {"桌子": 0.55, "书架": 0.30, "床": 0.08, "地板": 0.05, "沙发": 0.02},
        "人":  {"道路": 0.30, "草地": 0.25, "桌子": 0.15, "沙发": 0.15, "建筑": 0.10, "停车场": 0.05},
    })

    # prior_strength（先验强度）：场景先验在最终评分中的权重（weight）
    # 0.4 = 40% 先验 + 60% 显著性/检测反馈（feedback）
    # 值越大 → 越依赖"常识"；值越小 → 越依赖"实际看到的东西"
    prior_strength: float = 0.4


