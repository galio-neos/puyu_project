# 4. 显著性检测配置 — 定义"哪些区域视觉上最显眼"
# ============================================================================

@dataclass
class SaliencyConfig:
    """
    显著性检测（Saliency Detection）的参数配置。

    【什么是显著性（Saliency）？】
      显著性 = 一个区域在视觉上有多"突出"。
      比如白墙上的一个黑点 → 高显著性；均匀的蓝天 → 低显著性。
      显著性检测非常快（不需要 GPU（图形处理器）），可以在选择窗口前预计算。

    【Spectral Residual（谱残差法，简称 SR）原理（简化版）】
      1. FFT（Fast Fourier Transform，快速傅里叶变换）→ 得到频谱（spectrum）
      2. 频谱 = "常见模式" + "异常模式"
      3. 减去常见模式（均值滤波 / mean blur） → 剩下的"异常"就是显著区域
      4. IFFT（Inverse FFT，逆快速傅里叶变换）→ 得到显著性图（saliency map）
    """
    method: str = "spectral_residual"  # 使用的方法（目前仅支持 SR）
    sr_blur_size: int = 7              # 均值滤波核大小（kernel size）。越大 → 只保留越明显的显著性
    sr_fft_size: Tuple[int, int] = (64, 64)  # FFT 尺寸。缩到 64×64 再算 → 加速计算


