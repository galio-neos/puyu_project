"""
=============================================================================
配置模块 — 基于全景图像的无地图主动目标搜索
=============================================================================

【本文件的作用】
  集中管理项目中所有可调参数。修改参数只需要改这个文件，不必翻查其他代码。
  使用 Python 的 @dataclass（数据类装饰器），让每个配置类自动生成 __init__ 方法。

【初学者提示】
  - dataclass（数据类）是 Python 3.7+ 的特性，自动为类生成构造函数
  - field(default_factory=lambda: [...]) 用于给可变默认值（list/dict）
  - 修改任何参数后直接 python code/main.py 即可看到效果变化
=============================================================================
"""

from dataclasses import dataclass, field
from typing import Dict, List, Tuple, Optional
import numpy as np


# ============================================================================
# 1. 全景图参数 — 定义"我们要搜索的图像有多大"
# ============================================================================

@dataclass
class PanoramaConfig:
    """
    全景图 / 高分辨率图像的基础参数。
    在真实应用中，这里会被替换为实际拍摄的全景照片尺寸。
    """
    width: int = 1600              # 全景图宽度（像素）。1600px 约等于 5-6 个 200px 窗口并排
    height: int = 600              # 全景图高度（像素）。600px 约等于 3 个 200px 窗口堆叠
    synthetic: bool = True         # True = 用代码生成假全景图 / False = 加载真实图像


# ============================================================================
# 2. 观察窗口参数 — 定义"每次能看到多大一块"
# ============================================================================

@dataclass
class WindowConfig:
    """
    模拟视场受限相机的观察窗口。

    【关键概念】
      整个全景图是 1600×600，但每次只能看 200×200 的一小块。
      这就好比你在用望远镜看一幅巨幅壁画——每次只能看到局部，
      需要移动视线（选择下一个窗口）才能覆盖整个画面。
    """
    width: int = 200               # 窗口宽度（像素）
    height: int = 200              # 窗口高度（像素）

    # ------------------------------------------------------------------
    # 滑动步长（stride）：窗口每次移动多少像素
    # 步长 = 窗口大小的一半 → 相邻窗口有 50% 的重叠（overlap）
    # 例如：窗口 200×200，步长 100 → 在全景图上生成约 75 个候选窗口
    #        (1600-200)/100 + 1 = 15 列, (600-200)/100 + 1 = 5 行
    # ------------------------------------------------------------------
    stride_x: int = 100
    stride_y: int = 100

    # ------------------------------------------------------------------
    # 粗到细搜索（Coarse-to-Fine Search）的额外尺度参数
    # （由 I3_CoarseToFine 创新策略使用）
    #
    # coarse_scale（粗尺度）= 0.5：粗搜索时窗口缩小到 100×100（分辨率减半）
    #   → 覆盖范围更大，但细节更少，适合"快速扫一眼"
    #
    # fine_scales（精细尺度）= [1.0, 1.5, 2.0]：精细搜索时用三种尺度确认
    #   → 1.0 = 原始分辨率，1.5 = 放大 1.5 倍看细节
    # ------------------------------------------------------------------
    coarse_scale: float = 0.5
    fine_scales: List[float] = field(default_factory=lambda: [1.0, 1.5, 2.0])
#不直接写 fine_scales: List[float] = [1.0, 1.5, 2.0] ，因为所有实例共享一个list
#用default_factory 接受函数，让每次创建新实例时调用这个函数生成全新的列表，各实例互不影响

# ============================================================================
# 3. 目标检测配置 — 模拟"检测器觉得这个窗口里有目标的概率"
# ============================================================================

@dataclass
class DetectionConfig:
    """
    模拟目标检测器的行为参数。

    【为什么需要模拟？】
      在真实系统中，目标检测由 YOLO（You Only Look Once，实时目标检测模型）
      等深度学习模型完成。但在这个仿真项目中，我们用一个数学公式来模拟检测器的输出：
      置信度（confidence）= 0.95 × exp(-距离² / (2×80²)) + 随机噪声（noise）
      距离越大，confidence下降
      意思是：窗口离目标越近 → 置信度越高 → 越可能判定"找到了"
    """

    # ---- 模拟检测器的噪声（noise）参数 ----
    sim_noise_std: float = 0.15    # 噪声标准差（standard deviation）。模拟真实检测器的不确定性（越大越不稳定）
    sim_peak_confidence: float = 0.95  # 最高置信度（peak confidence）。窗口正好对准目标时能达到的最大值
    sim_decay_sigma: float = 80.0  # 高斯衰减（Gaussian decay）的 σ（sigma）。距离每增加 80px，置信度约降为 60%

    # ---- 决策阈值（threshold） ----
    found_threshold: float = 0.70  # 置信度 > 0.70 → 认为"这个窗口里有目标"（用于评估）
    stop_threshold: float = 0.85   # 置信度 > 0.85 → 立即停止搜索（表示"确定找到了"）


